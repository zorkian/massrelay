use std::{
    env,
    fmt::Write as _,
    fs,
    io::{self, Write as _},
    path::{Path, PathBuf},
    process::{Command, Output},
};

use anyhow::{Context, Result, bail, ensure};
use directories::BaseDirs;
use sha2::{Digest, Sha256};
use tempfile::NamedTempFile;

use crate::{ServiceAction, default_state_dir, device, storage};

const GENERATED: &str = "# Generated by massrelay install\n";

pub fn install(dir: &Path) -> Result<()> {
    device::check_enrolled(dir)?;
    let dir = dir
        .canonicalize()
        .context("resolve the device state directory")?;
    let (units, unit) = profile_unit(&dir)?;
    let path = units.join(&unit);
    let log = dir.join("connections.jsonl");
    let binary = env::current_exe().context("find the running MassRelay binary")?;
    let contents = render(&binary, &dir, &log)?;

    systemctl(&["show-environment"]).context("connect to your systemd user manager")?;
    let was_active = user_command(&["is-active", "--quiet", &unit])?
        .status
        .success();
    let was_enabled = user_command(&["is-enabled", "--quiet", &unit])?
        .status
        .success();
    let previous = read_unit(&path)?;
    if !was_active {
        let _lock = storage::lock(&dir).context("stop the foreground massrelay run first")?;
    } else {
        ensure!(previous.is_some(), "an existing service uses {unit}");
    }

    fs::create_dir_all(&units)?;
    write_unit(&path, contents.as_bytes())?;
    let applied = (|| {
        systemctl(&["daemon-reload"])?;
        systemctl(&["restart", &unit])?;
        systemctl(&["enable", &unit])
    })();
    if let Err(error) = applied {
        let restore = (|| {
            if let Some(previous) = previous {
                if !was_active {
                    systemctl(&["stop", &unit])?;
                }
                if !was_enabled {
                    systemctl(&["disable", &unit])?;
                }
                write_unit(&path, &previous)?;
            } else {
                // Cancel any activation or enablement before removing a failed new unit.
                let _ = systemctl(&["disable", "--now", &unit]);
                fs::remove_file(&path)?;
            }
            systemctl(&["daemon-reload"])?;
            if was_active {
                systemctl(&["restart", &unit])?;
            }
            Ok::<_, anyhow::Error>(())
        })();
        if let Err(restore) = restore {
            return Err(error.context(format!("could not restore systemd service: {restore:#}")));
        }
        return Err(error);
    }
    println!("Started {unit}");
    println!("Event log       {}", log.display());
    println!("Service log     journalctl --user -u {unit}");
    Ok(())
}

pub fn control(dir: &Path, action: ServiceAction) -> Result<()> {
    let dir = dir
        .canonicalize()
        .context("resolve the device state directory")?;
    let (units, unit) = profile_unit(&dir)?;
    let result = (|| {
        let path = units.join(&unit);
        ensure!(
            read_unit(&path)?.is_some(),
            "no installed service for this profile. Run massrelay install first"
        );
        systemctl(&["show-environment"]).context("connect to your systemd user manager")?;
        if !matches!(action, ServiceAction::Stop)
            && !user_command(&["is-active", "--quiet", &unit])?
                .status
                .success()
        {
            let _lock = storage::lock(&dir).context("stop the foreground massrelay run first")?;
        }
        systemctl(&[action.name(), &unit])
    })();
    action.record(&dir.join("connections.jsonl"), &result);
    result?;
    println!("{} {unit}", action.completed());
    Ok(())
}

fn profile_unit(dir: &Path) -> Result<(PathBuf, String)> {
    let default = default_state_dir()?.canonicalize().ok();
    let unit = unit_name(dir, default.as_deref());
    let user = BaseDirs::new().context("cannot find the user configuration directory")?;
    Ok((user.config_dir().join("systemd/user"), unit))
}

fn read_unit(path: &Path) -> Result<Option<Vec<u8>>> {
    match fs::symlink_metadata(path) {
        Ok(metadata) if metadata.is_file() => {
            let previous = fs::read(path)?;
            ensure!(
                previous.starts_with(GENERATED.as_bytes()),
                "an existing service uses {}",
                path.display()
            );
            Ok(Some(previous))
        }
        Ok(_) => bail!("expected a regular file at {}", path.display()),
        Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(None),
        Err(error) => Err(error.into()),
    }
}

fn unit_name(dir: &Path, default: Option<&Path>) -> String {
    if default == Some(dir) {
        "massrelay-client.service".into()
    } else {
        let hash = Sha256::digest(dir.as_os_str().as_encoded_bytes());
        format!("massrelay-client-{hash:x}.service")
    }
}

fn render(binary: &Path, dir: &Path, log: &Path) -> Result<String> {
    // The colon prefix disables systemd's environment expansion for this command.
    let binary = argument(binary, ":")?;
    let dir = argument(dir, "")?;
    let log = argument(log, "")?;
    Ok(format!(
        "{GENERATED}\
[Unit]\n\
Description=MassRelay client\n\
\n\
[Service]\n\
Type=exec\n\
ExecStart={binary} --state-dir {dir} run --log-file {log}\n\
Restart=on-failure\n\
\n\
[Install]\n\
WantedBy=default.target\n"
    ))
}

fn argument(path: &Path, prefix: &str) -> Result<String> {
    let text = path
        .to_str()
        .with_context(|| format!("path is not UTF-8: {}", path.display()))?;
    let mut escaped = format!("\"{prefix}");
    for ch in text.chars() {
        match ch {
            '%' => escaped.push_str("%%"),
            '\\' => escaped.push_str("\\\\"),
            '"' => escaped.push_str("\\\""),
            ch if ch.is_control() => write!(escaped, "\\u{:04x}", u32::from(ch))?,
            ch => escaped.push(ch),
        }
    }
    escaped.push('"');
    Ok(escaped)
}

fn write_unit(path: &Path, contents: &[u8]) -> Result<()> {
    let mut staged = NamedTempFile::new_in(path.parent().expect("unit directory"))?;
    staged.write_all(contents)?;
    staged.as_file().sync_all()?;
    staged
        .persist(path)
        .with_context(|| format!("save {}", path.display()))?;
    Ok(())
}

fn user_command(args: &[&str]) -> Result<Output> {
    Command::new("systemctl")
        .arg("--user")
        .args(args)
        .output()
        .context("run systemctl --user")
}

fn systemctl(args: &[&str]) -> Result<()> {
    let output = user_command(args)?;
    ensure!(
        output.status.success(),
        "systemctl --user {} failed ({}): {}",
        args.join(" "),
        output.status,
        String::from_utf8_lossy(&output.stderr).trim()
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn unit_uses_the_selected_profile_and_quotes_paths() -> Result<()> {
        let binary = Path::new("/home/A & B/bin/massrelay");
        let dir = Path::new("/home/A & B/$HOME/%i \"profile\"");
        let log = dir.join("connections.jsonl");
        assert_eq!(unit_name(dir, Some(dir)), "massrelay-client.service");
        assert_ne!(unit_name(dir, None), unit_name(log.as_path(), None));
        let source = render(binary, dir, &log)?;
        assert!(source.lines().any(|line| line
            == r#"ExecStart=":/home/A & B/bin/massrelay" --state-dir "/home/A & B/$HOME/%%i \"profile\"" run --log-file "/home/A & B/$HOME/%%i \"profile\"/connections.jsonl""#));
        Ok(())
    }
}
