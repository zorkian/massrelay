    #[test]
    #[ignore = "uses the systemd user manager; set MASSRELAY_ACCEPTANCE_SYSTEMD_USER=1"]
    fn a_queued_install_outlives_the_session_that_queued_it() -> Result<()> {
        use std::{os::unix::fs::PermissionsExt, time::Instant};

        // The release workflow runs every ignored test, on runners that may have no manager.
        if env::var_os("MASSRELAY_ACCEPTANCE_SYSTEMD_USER").is_none() {
            return Ok(());
        }
        let temp = tempfile::tempdir()?;
        let root = temp.path().canonicalize()?;
        let id = format!("{:x}", Sha256::digest(root.as_os_str().as_encoded_bytes()));
        let session = format!("massrelay-test-session-{}.service", &id[..16]);
        let finisher = format!("massrelay-test-install-{}.service", &id[..16]);
        // Ends the session that queued it, as a restart of the daemon would, and goes on.
        let program = root.join("finisher");
        fs::write(
            &program,
            format!(
                r#"#!/bin/sh
set -eu
[ "$*" = "--state-dir $2 install --yes" ]
[ -z "${{MASSRELAY_SHELL_HOST+x}}" ]
[ -z "${{SSH_CONNECTION+x}}" ]
[ "$MASSRELAY_QUEUED_INSTALL" = 'the approved $HOME %i' ]
systemctl --user is-active --quiet {session}
systemctl --user stop {session}
! systemctl --user is-active --quiet {session}
echo finished >"$2/finished"
"#
            ),
        )?;
        fs::set_permissions(&program, fs::Permissions::from_mode(0o700))?;
        let tests = env::current_exe()?;
        let (_, module) = module_path!().split_once("::").context("the test module")?;
        let setting = |name: &str, value: &str| format!("--setenv={name}={value}");
        let root_text = root.to_str().context("a UTF-8 temporary directory")?;
        let started = user_manager("systemd-run")
            .args(["--collect", "--unit", &session])
            .arg(setting("MASSRELAY_TEST_SESSION", root_text))
            .arg(setting("MASSRELAY_TEST_INSTALL_UNIT", &finisher))
            .arg(setting(crate::private::HOST_ENV, "1"))
            .arg("--")
            .arg(&tests)
            .arg(format!("{module}::queueing_session"))
            .args(["--exact", "--ignored"])
            .output()?;
        succeeded(&["systemd-run"], started)?;
        let deadline = Instant::now() + Duration::from_secs(30);
        while !root.join("finished").exists() {
            if Instant::now() >= deadline {
                let _ = bounded(&["stop", &session, &finisher]);
                bail!("the queued install did not finish after ending its session");
            }
            std::thread::sleep(Duration::from_millis(50));
        }
        assert!(!root.join("session-survived").exists());
        Ok(())
    }

    #[test]
    fn a_finished_install_that_does_not_serve_gives_way_to_the_previous_service() -> Result<()> {
        use std::cell::RefCell;

        let temp = tempfile::tempdir()?;
        let dir = temp.path().join("profile");
        let units = temp.path().to_owned();
        let unit = unit_name(&dir, None);
        let path = units.join(&unit);
        let log = dir.join("connections.jsonl");
        let (old, new) = (Path::new("/opt/previous"), Path::new("/opt/replacement"));
        let previous = render(old, &dir, &log)?;
        // Install over the previous unit, with a runtime that answers only while the unit
        // starts one of `answering`.
        let install = |answering: &[&str], finishing: bool| {
            write_unit(&path, previous.as_bytes())?;
            let prepared = Prepared {
                dir: dir.clone(),
                units: units.clone(),
                unit: unit.clone(),
                path: path.clone(),
                log: log.clone(),
                binary: new.into(),
                contents: render(new, &dir, &log)?,
                was_active: true,
                was_enabled: true,
                loaded: Default::default(),
                loaded_as_written: false,
                previous: unit_file(&path)?,
            };
            let asked = RefCell::new(Vec::new());
            let systemctl = |args: &[&str]| {
                asked.borrow_mut().push(args[0].to_owned());
                Ok(())
            };
            let serves = |program: Option<&Path>| {
                let program = program.map_or_else(String::new, |path| path.display().to_string());
                asked.borrow_mut().push(format!("serves {program}"));
                let unit = fs::read_to_string(&path)?;
                ensure!(
                    answering.iter().any(|program| unit.contains(program)),
                    "nothing answers"
                );
                Ok(())
            };
            let verify: Verify = if finishing { Some(&serves) } else { None };
            let result = register(prepared, &systemctl, verify).map_err(|e| format!("{e:#}"));
            anyhow::Ok((result, asked.into_inner(), fs::read_to_string(&path)?))
        };
        let replacing = [
            "daemon-reload",
            "restart",
            "enable",
            "serves /opt/replacement",
        ];
        let restoring = ["daemon-reload", "reset-failed", "restart", "serves "];

        let (result, asked, left) = install(&["/opt/replacement"], true)?;
        assert!(result.is_ok(), "{result:?}");
        assert_eq!(asked, replacing);
        assert_ne!(left, previous);

        let (result, asked, left) = install(&["/opt/previous"], true)?;
        let error = result.unwrap_err();
        assert!(error.contains("the new service did not come up"), "{error}");
        assert!(error.contains("restored and answers"), "{error}");
        assert_eq!(asked, [replacing, restoring].concat());
        assert_eq!(left, previous);

        // A restored service that does not answer either is not called restored.
        let (result, _, left) = install(&[], true)?;
        let error = result.unwrap_err();
        assert!(error.contains("could not restore"), "{error}");
        assert!(
            error.contains("the restored service did not come up"),
            "{error}"
        );
        assert_eq!(left, previous);

        // A command that someone watches installs as before.
        let (result, asked, _) = install(&[], false)?;
        assert!(result.is_ok(), "{result:?}");
        assert_eq!(asked, replacing[..3]);
        Ok(())
    }

    #[test]
    fn unit_uses_the_selected_profile_and_quotes_paths() -> Result<()> {
        let binary = Path::new("/home/A & B/bin/massrelay");
        let dir = Path::new("/home/A & B/$HOME/%i \"profile\"");
        let log = dir.join("connections.jsonl");
        assert_eq!(unit_name(dir, Some(dir)), "massrelay-client.service");
        assert_ne!(unit_name(dir, None), unit_name(log.as_path(), None));
        let source = render(binary, dir, &log)?;
        assert!(source.lines().any(|line| line
            == r#"ExecStart=":/home/A & B/bin/massrelay" --state-dir "/home/A & B/$HOME/%%i \"profile\"" run --log-file "/home/A & B/$HOME/%%i \"profile\"/connections.jsonl""#));
        // An update only replaces the exact program the unit starts for this profile.
        assert!(starts(&source, binary, dir)?);
        assert!(!starts(
            &source,
            Path::new("/home/A & B/bin/massrelay2"),
            dir
        )?);
        assert!(!starts(&source, Path::new("/home/A & B/bin/mass"), dir)?);
        assert!(!starts(&source, binary, &log)?);
        let twice = format!("{source}ExecStart=/bin/true\n");
        assert!(!starts(&twice, binary, dir)?);

        // The manager's loaded view must agree: this is what it prints for that unit.
        let shown = |path: &str, reload: &str| {
            format!(
                "ExecStart={{ path={path} ; argv[]={path} --state-dir /home/A & B/$HOME/%i \"profile\" run --log-file /home/A & B/$HOME/%i \"profile\"/connections.jsonl ; ignore_errors=no ; start_time=[n/a] ; stop_time=[n/a] ; pid=0 ; code=(null) ; status=0/0 }}\nNeedDaemonReload={reload}\n"
            )
        };
        let current = shown("/home/A & B/bin/massrelay", "no");
        assert!(loaded(&current, binary, dir)?);
        // A drop-in that starts another program, or adds a command.
        assert!(!loaded(&shown("/opt/other/massrelay", "no"), binary, dir)?);
        let added = format!("ExecStart={{ path=/bin/true ; argv[]=/bin/true ; }}\n{current}");
        assert!(!loaded(&added, binary, dir)?);
        // Only a unit that is plainly not running counts as stopped.
        use crate::update::Manager;
        let state = |active: &str, pid: u32| {
            manager_state(&format!("MainPID={pid}\nActiveState={active}\n")).unwrap()
        };
        assert_eq!(state("active", 4242), Manager::Running(4242));
        assert_eq!(state("inactive", 0), Manager::Stopped);
        assert_eq!(state("failed", 0), Manager::Stopped);
        for between in ["activating", "deactivating", "reloading", "maintenance"] {
            assert!(
                matches!(state(between, 0), Manager::Pending(_)),
                "{between}"
            );
            assert!(
                matches!(state(between, 4242), Manager::Pending(_)),
                "{between}"
            );
        }
        assert!(matches!(state("active", 0), Manager::Pending(_)));
        assert!(manager_state("ActiveState=active\n").is_err());

        // A unit file changed on disk that the manager has not loaded yet.
        assert!(!loaded(
            &shown("/home/A & B/bin/massrelay", "yes"),
            binary,
            dir
        )?);
        assert!(!loaded(&current, binary, &log)?);
        Ok(())
    }
