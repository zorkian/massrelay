const GENERATED: &str = "# Generated by massrelay install\n";
/// How long a stop may take: longer than the manager's own limit, after which it kills.
const STOP_LIMIT: Duration = Duration::from_secs(120);
const HOSTED: &str = "this command depends on the service it would remove: it runs under that \
    service, such as in a MassRelay shell on this device, and would end partway. Nothing was \
    changed. Run 'massrelay uninstall' from a local terminal on this device";
const CHANGED: &str = "the background service is no longer as it was shown, so it was not \
    touched. Run 'massrelay uninstall' again";
const INSTALL_CHANGED: &str = "the background service, or what an install would write, is no \
    longer as it was shown, so nothing was installed. Run 'massrelay install' again";

/// Everything `install` settles before it changes anything, and so all that a confirmation of
/// it approves.
#[derive(Debug, PartialEq, Eq)]
struct Prepared {
    dir: PathBuf,
    units: PathBuf,
    unit: String,
    path: PathBuf,
    log: PathBuf,
    binary: PathBuf,
    contents: String,
    was_active: bool,
    was_enabled: bool,
    /// The file and commands the manager has loaded for the unit.
    loaded: (String, Vec<String>),
    loaded_as_written: bool,
    previous: Option<UnitFile>,
}

impl Prepared {
    /// Look, changing nothing, at what an install of `binary` for the profile in the
    /// canonical `dir` would replace.
    fn read(
        dir: PathBuf,
        (units, unit): (PathBuf, String),
        binary: PathBuf,
        systemctl: &dyn Fn(&[&str]) -> Result<Output>,
    ) -> Result<Self> {
        let path = units.join(&unit);
        let log = dir.join("connections.jsonl");
        let contents = render(&binary, &dir, &log)?;
        let required = |args: &[&str]| succeeded(args, systemctl(args)?);

        required(&["show-environment"]).context("connect to your systemd user manager")?;
        let was_active = systemctl(&["is-active", "--quiet", &unit])?
            .status
            .success();
        let was_enabled = systemctl(&["is-enabled", "--quiet", &unit])?
            .status
            .success();
        let shown = required(&[
            "show",
            "--property=FragmentPath",
            "--property=ExecStart",
            "--property=NeedDaemonReload",
            "--property=DropInPaths",
            &unit,
        ])?;
        let shown = String::from_utf8_lossy(&shown.stdout);
        let fragment = property(&shown, "FragmentPath").unwrap_or_default();
        let loaded = (fragment.to_owned(), loaded_commands(&shown));
        let previous = unit_file(&path)?;
        Ok(Self {
            dir,
            units,
            unit,
            path,
            log,
            binary,
            contents,
            was_active,
            was_enabled,
            loaded,
            loaded_as_written: property(&shown, "NeedDaemonReload").ok() == Some("no")
                && property(&shown, "DropInPaths").ok() == Some(""),
            previous,
        })
    }
}

fn prepare(dir: &Path) -> Result<Prepared> {
    let dir = dir
        .canonicalize()
        .context("resolve the device state directory")?;
    let target = profile_unit(&dir)?;
    let binary = env::current_exe().context("find the running MassRelay binary")?;
    Prepared::read(dir, target, binary, &user_command)
}

/// An install as shown for confirmation, which displays as the changes it would make.
pub struct InstallPlan {
    shown: Prepared,
    /// The runtime whose service registration this install leaves alone.
    kept: Option<Identity>,
}

impl fmt::Display for InstallPlan {
    fn fmt(&self, formatter: &mut fmt::Formatter) -> fmt::Result {
        let Prepared {
            dir,
            unit,
            path,
            log,
            binary,
            was_active,
            was_enabled,
            previous,
            ..
        } = &self.shown;
        if self.keeps() {
            write!(
                formatter,
                "Keep the systemd user service {unit} running without a restart, using its \
                 existing registration at {}",
                path.display()
            )?;
            if !was_enabled {
                write!(
                    formatter,
                    "\nSystemd does not report {unit} enabled to start at login"
                )?;
            }
            return Ok(());
        }
        let write = if previous.is_some() {
            "Replace"
        } else {
            "Write"
        };
        let start = if *was_active { "restart" } else { "start" };
        write!(
            formatter,
            "{write} the systemd user unit {}\n\
             Reload the systemd user manager, then {start} and enable {unit}\n\
             It runs {} for the profile in {} and records events in {}",
            path.display(),
            binary.display(),
            dir.display(),
            log.display()
        )
    }
}

/// What `install` would write and start. Changes nothing, and so leaves to `apply` the checks
/// that open the profile's files for writing.
pub fn plan_install(dir: &Path) -> Result<InstallPlan> {
    prepare(dir).map(InstallPlan::new)
}

impl InstallPlan {
    fn new(shown: Prepared) -> Self {
        Self { shown, kept: None }
    }

    /// For a command in a session that depends on `runtime`, which has to be this profile's
    /// service. Keep the running registration when it already serves this version or
    /// when we cannot establish that a restart can be rolled back.
    pub fn carried_by(&mut self, runtime: &Identity) -> Result<()> {
        self.inspect_carrier(runtime, &user_command)
    }

    fn inspect_carrier(
        &mut self,
        runtime: &Identity,
        systemctl: &dyn Fn(&[&str]) -> Result<Output>,
    ) -> Result<()> {
        let Prepared {
            dir,
            unit,
            path,
            binary,
            log,
            was_active,
            was_enabled,
            loaded: (fragment, _),
            loaded_as_written,
            previous,
            ..
        } = &self.shown;
        let args = [
            "show",
            "--property=MainPID",
            "--property=ExecStart",
            "--property=NeedDaemonReload",
            unit,
        ];
        let shown = succeeded(&args, systemctl(&args)?)?;
        let shown = String::from_utf8_lossy(&shown.stdout);
        ensure!(
            *was_active && property(&shown, "MainPID")?.parse() == Ok(runtime.pid),
            installer::NOT_THE_SERVICE
        );
        if *was_enabled && installer::is_this_program(runtime, binary) {
            self.kept = Some(runtime.clone());
            return Ok(());
        }
        let running = runtime
            .executable
            .as_deref()
            .map(Path::new)
            .filter(|program| program.is_file());
        let rollback = match (running, previous) {
            (Some(program), Some(file)) => {
                file.contents == render(program, dir, log)?.as_bytes()
                    && loaded(&shown, program, dir)?
            }
            _ => false,
        };
        let restorable = *loaded_as_written && same_place(Path::new(fragment), path) && rollback;
        self.kept = (!restorable).then(|| runtime.clone());
        Ok(())
    }

    /// Whether applying this leaves the running service alone.
    pub fn keeps(&self) -> bool {
        self.kept.is_some()
    }

    /// Everything a confirmation of this approves, to compare across processes.
    pub fn approval(&self) -> String {
        format!("{:?} {:?}", self.shown, self.kept)
    }

    /// Where a queued install says what it did.
    pub fn log(&self) -> String {
        format!("journalctl --user -u {}", install_unit(&self.shown.unit))
    }

    /// Install and start the service, if what it would replace and write is still as it was
    /// shown. Returns the canonical state directory the service was installed for.
    pub fn apply(self) -> Result<PathBuf> {
        self.perform(None)
    }

    fn perform(self, serves: Verify) -> Result<PathBuf> {
        cli::check_enrolled(&self.shown.dir)?;
        let found = self.confirm(prepare(&self.shown.dir)?)?;
        let Some(runtime) = &self.kept else {
            return register(found, &systemctl, serves);
        };
        let mut found = Self::new(found);
        found.carried_by(runtime)?;
        ensure!(found.keeps(), INSTALL_CHANGED);
        let Prepared {
            dir,
            unit,
            log,
            was_enabled,
            ..
        } = found.shown;
        crate::update::say(format!(
            "Kept {unit} running\nEvent log       {}",
            log.display()
        ));
        if !was_enabled {
            crate::update::say(format!(
                "Systemd does not report {unit} enabled to start at login"
            ));
        }
        Ok(dir)
    }

    /// `apply` in the process a `queue` started, which counts a start only once `serves`
    /// finds the runtime answering.
    pub fn finish(self, serves: &dyn Fn(Option<&Path>) -> Result<()>) -> Result<PathBuf> {
        self.perform(Some(serves))
    }

    /// Hand this install, as `approval` names it, to a unit of its own, which neither the
    /// service's restart nor this session's end reaches. Returns where it logs.
    pub fn queue(self, approval: &str) -> Result<String> {
        cli::check_enrolled(&self.shown.dir)?;
        let found = self.confirm(prepare(&self.shown.dir)?)?;
        let log = self.log();
        let unit = install_unit(&found.unit);
        let mut environment = vec![(installer::QUEUED, OsString::from(approval))];
        // What decides where the unit and the profile are found, as this command found them.
        environment.extend(
            ["HOME", "XDG_CONFIG_HOME", "XDG_DATA_HOME"]
                .into_iter()
                .filter_map(|name| Some((name, env::var_os(name)?))),
        );
        let arguments = ["install", "--yes"];
        start_detached(&unit, &found.binary, &found.dir, &arguments, &environment)
            .context("start a detached MassRelay install with systemd-run")?;
        Ok(log)
    }

    /// Require what an install finds now to be what was shown.
    fn confirm(&self, found: Prepared) -> Result<Prepared> {
        ensure!(found == self.shown, INSTALL_CHANGED);
        Ok(found)
    }
}

fn install_unit(unit: &str) -> String {
    unit.replacen("massrelay-client", "massrelay-install", 1)
}

/// Run `program --state-dir dir ARGUMENTS` as the transient user unit `unit`, outside the
/// daemon's and every session's lifetime and without the variables that place a command in a
/// session. One such unit runs at a time; the manager forgets it once it ends.
fn start_detached(
    unit: &str,
    program: &Path,
    dir: &Path,
    arguments: &[&str],
    environment: &[(&str, OsString)],
) -> Result<()> {
    let state = dir
        .to_str()
        .context("the state directory is not UTF-8")?
        .replace('$', "$$");
    let unset = unset_session();
    let mut command = user_manager("systemd-run");
    command.args(["--collect", "--unit", unit]);
    command.args(["--property=Type=exec", "--property", &unset]);
    for (name, value) in environment {
        let mut setting = OsString::from(format!("--setenv={name}="));
        setting.push(value);
        command.arg(setting);
    }
    command
        .arg("--")
        .arg(program)
        .args(["--state-dir", &state])
        .args(arguments);
    let queued = crate::update::run_within(&mut command, crate::update::MANAGER_LIMIT)
        .context("run systemd-run --user")?;
    ensure!(
        queued.success,
        "could not start {unit}: {}. Check 'journalctl --user -u {unit}'",
        queued.stderr.trim()
    );
    Ok(())
}

fn register(
    prepared: Prepared,
    systemctl: &dyn Fn(&[&str]) -> Result<()>,
    serves: Verify,
) -> Result<PathBuf> {
    let Prepared {
        dir,
        units,
        unit,
        path,
        log,
        binary,
        contents,
        was_active,
        was_enabled,
        previous,
        ..
    } = prepared;

    ensure!(
        !was_active || previous.is_some(),
        "an existing service uses {unit}"
    );
    if !was_active {
        let _lock = cli::claim_owner(&dir).context("stop the foreground massrelay run first")?;
    }
    fs::create_dir_all(&units)?;
    write_unit(&path, contents.as_bytes())?;
    let applied = (|| {
        systemctl(&["daemon-reload"])?;
        systemctl(&["restart", &unit])?;
        systemctl(&["enable", &unit])?;
        if let Some(serves) = serves {
            serves(Some(&binary)).context("the new service did not come up")?;
        }
        Ok::<_, anyhow::Error>(())
    })();
    if let Err(error) = applied {
        let restore = (|| {
            if let Some(previous) = previous {
                if !was_active {
                    systemctl(&["stop", &unit])?;
                }
                if !was_enabled {
                    systemctl(&["disable", &unit])?;
                }
                write_unit(&path, &previous.contents)?;
            } else {
                // Cancel any activation or enablement before removing a failed new unit.
                let _ = systemctl(&["disable", "--now", &unit]);
                fs::remove_file(&path)?;
            }
            systemctl(&["daemon-reload"])?;
            if was_active {
                if serves.is_some() {
                    // One that kept failing may have used up the unit's start limit.
                    let _ = systemctl(&["reset-failed", &unit]);
                }
                systemctl(&["restart", &unit])?;
                if let Some(serves) = serves {
                    serves(None).context("the restored service did not come up")?;
                }
            }
            Ok::<_, anyhow::Error>(())
        })();
        if let Err(restore) = restore {
            return Err(error.context(format!("could not restore systemd service: {restore:#}")));
        }
        return Err(match serves {
            Some(_) if was_active => error.context("the previous service was restored and answers"),
            _ => error,
        });
    }
    println!("Started {unit}");
    println!("Event log       {}", log.display());
    println!("Service log     journalctl --user -u {unit}");
    Ok(dir)
}

pub fn control(dir: &Path, action: ServiceAction) -> Result<()> {
    let dir = dir
        .canonicalize()
        .context("resolve the device state directory")?;
    let (units, unit) = profile_unit(&dir)?;
    let result = (|| {
        let path = units.join(&unit);
        ensure!(
            read_unit(&path)?.is_some(),
            "no installed service for this profile. Run massrelay install first"
        );
        systemctl(&["show-environment"]).context("connect to your systemd user manager")?;
        if !matches!(action, ServiceAction::Stop)
            && !user_command(&["is-active", "--quiet", &unit])?
                .status
                .success()
        {
            let _lock =
                cli::claim_owner(&dir).context("stop the foreground massrelay run first")?;
        }
        systemctl(&[action.name(), &unit])
    })();
    action.record(&dir.join("connections.jsonl"), &result);
    result?;
    println!("{} {unit}", action.completed());
    Ok(())
}

/// A removal as shown for confirmation, which displays as the changes it would make.
pub struct UninstallPlan {
    /// The canonical state directory, and the unit `install` gives it.
    dir: PathBuf,
    unit: String,
    path: PathBuf,
    found: Found,
    text: String,
}

impl fmt::Display for UninstallPlan {
    fn fmt(&self, formatter: &mut fmt::Formatter) -> fmt::Result {
        formatter.write_str(&self.text)
    }
}

/// What there is to stop and remove for this profile. Changes nothing.
pub fn plan_uninstall(dir: &Path) -> Result<UninstallPlan> {
    let dir = dir
        .canonicalize()
        .context("resolve the device state directory")?;
    let (units, unit) = profile_unit(&dir)?;
    let path = units.join(&unit);
    let (found, text) = manage(&dir, &unit, &path, |removal| {
        let found = removal.inspect()?;
        let text = removal.describe(&found);
        Ok((found, text))
    })?;
    Ok(UninstallPlan {
        dir,
        unit,
        path,
        found,
        text,
    })
}

impl UninstallPlan {
    /// Stop this profile's service and remove its unit, if both are still as they were shown.
    /// The profile, its keys, its logs and any drop-in settings are kept. A plan that showed
    /// nothing to remove succeeds while there is still nothing.
    ///
    /// A hangup is ignored from the first change until this command ends: a terminal that
    /// reached this device through the service goes away when it stops.
    pub fn apply(self) -> Result<()> {
        manage(&self.dir, &self.unit, &self.path, |removal| {
            let found = removal.confirm(&self.found)?;
            // SAFETY: ignoring a signal installs no handler.
            unsafe { libc::signal(libc::SIGHUP, libc::SIG_IGN) };
            let done = removal.remove(found)?;
            // The terminal may be gone, which must not turn a finished removal into a panic.
            let _ = writeln!(io::stdout(), "{done}");
            Ok(())
        })
    }
}

/// Look at one profile's service through the real user manager.
fn manage<T>(
    dir: &Path,
    unit: &str,
    path: &Path,
    work: impl FnOnce(&Removal) -> Result<T>,
) -> Result<T> {
    let cgroups =
        fs::read_to_string("/proc/self/cgroup").context("find this command's control group")?;
    work(&Removal {
        dir,
        path,
        unit,
        cgroups: &cgroups,
        shell_host: env::var(crate::private::HOST_ENV)
            .ok()
            .and_then(|value| value.parse().ok()),
        systemctl: &|args| {
            let limit = if args.first() == Some(&"stop") {
                STOP_LIMIT
            } else {
                crate::update::MANAGER_LIMIT
            };
            crate::update::run_within(user_manager("systemctl").args(args), limit)
                .with_context(|| format!("run systemctl --user {}", args.join(" ")))
        },
    })
}

/// What there is to remove for a profile.
#[derive(Debug, PartialEq, Eq)]
enum Found {
    /// No unit file, and nothing the manager still has of one.
    Nothing { unreachable: bool },
    /// The generated unit file, and the commands the manager has loaded for the unit.
    Unit { file: UnitFile, loaded: Vec<String> },
    /// The file is gone, but the manager still has what it loaded from it.
    Orphan { loaded: Vec<String> },
}

impl Found {
    /// Whether removing this is removing `shown`.
    fn is(&self, shown: &Self) -> bool {
        matches!((self, shown), (Self::Nothing { .. }, Self::Nothing { .. })) || self == shown
    }
}

/// A unit file as it was read: its bytes, and which writing of the file held them.
#[derive(Debug, PartialEq, Eq)]
struct UnitFile {
    contents: Vec<u8>,
    /// Device, inode and modification time. An install replaces the file, even with the
    /// same bytes.
    written: (u64, u64, SystemTime),
}

/// The removal of one profile's unit.
struct Removal<'a> {
    /// The canonical state directory.
    dir: &'a Path,
    unit: &'a str,
    /// Where `install` writes the unit.
    path: &'a Path,
    /// This command's `/proc/self/cgroup`.
    cgroups: &'a str,
    /// The runtime serving the MassRelay shell this command says it is in.
    shell_host: Option<u32>,
    /// Runs one `systemctl --user` request, within a time limit.
    systemctl: &'a dyn Fn(&[&str]) -> Result<crate::update::Finished>,
}

impl Removal<'_> {
    /// Establish that everything to be stopped or removed is this profile's, and that doing so
    /// is safe now. Changes nothing.
    fn inspect(&self) -> Result<Found> {
        let (unit, path) = (self.unit, self.path.display());
        let file = unit_file(self.path)?;
        if let Some(file) = &file {
            ensure!(
                runs_profile(&String::from_utf8_lossy(&file.contents), self.dir)?,
                "{path} does not run the profile in {}; nothing was changed",
                self.dir.display()
            );
        }
        let shown = self.must(&[
            "show",
            "--property=LoadState",
            "--property=ActiveState",
            "--property=MainPID",
            "--property=FragmentPath",
            "--property=ExecStart",
            unit,
        ]);
        let shown = match shown {
            Ok(shown) => shown,
            Err(_) if file.is_none() => return Ok(Found::Nothing { unreachable: true }),
            Err(error) => {
                return Err(error.context(
                    "could not ask your systemd user manager about the service, so nothing was \
                     changed",
                ));
            }
        };
        let active = !stopped(&shown)?;
        // The file the manager loaded the unit from, if it has it loaded from one.
        let fragment = property(&shown, "FragmentPath").unwrap_or_default();
        ensure!(
            fragment.is_empty() || same_place(Path::new(fragment), self.path),
            "your systemd user manager has {unit} from {fragment}, not from {path}; nothing was \
             changed"
        );
        let found = match file {
            Some(file) => {
                ensure!(
                    !active || !fragment.is_empty(),
                    "{unit} is running, but not from {path}; nothing was changed"
                );
                Found::Unit {
                    file,
                    loaded: loaded_commands(&shown),
                }
            }
            None if fragment.is_empty() && !active => {
                return Ok(Found::Nothing { unreachable: false });
            }
            None => {
                ensure!(
                    loaded_for(&shown, self.dir)?,
                    "{unit} is still known to your systemd user manager, but {path} is gone and \
                     what it runs cannot be matched to this profile; nothing was changed. Stop \
                     it with 'systemctl --user stop {unit}'"
                );
                Found::Orphan {
                    loaded: loaded_commands(&shown),
                }
            }
        };

        let main = property(&shown, "MainPID")
            .ok()
            .and_then(|pid| pid.parse::<u32>().ok())
            .filter(|&pid| pid != 0);
        ensure!(
            !in_unit(self.cgroups, unit) && (main.is_none() || main != self.shell_host),
            HOSTED
        );
        // A queued update may be exchanging the program, and starts the service itself.
        let update = unit.replacen("massrelay-client", "massrelay-update", 1);
        ensure!(
            stopped(&self.must(&["show", "--property=ActiveState", &update])?)?,
            "an update of this service is queued or running as {update}; nothing was changed. \
             Follow it with 'journalctl --user -u {update}' and run 'massrelay uninstall' once \
             it has finished"
        );
        Ok(found)
    }

    /// Inspect again, and require what is there now to be what was shown.
    fn confirm(&self, shown: &Found) -> Result<Found> {
        let found = self.inspect()?;
        ensure!(found.is(shown), CHANGED);
        Ok(found)
    }

    fn describe(&self, found: &Found) -> String {
        let (unit, path, dir) = (self.unit, self.path.display(), self.dir.display());
        let mut text = match found {
            Found::Nothing { unreachable } => {
                let mut text = format!(
                    "No systemd user service to remove for the profile in {dir}: there is no \
                     unit file at {path}"
                );
                if *unreachable {
                    write!(
                        text,
                        "\nThe systemd user manager could not be asked about a loaded {unit}"
                    )
                    .expect("write to string");
                }
                return text;
            }
            Found::Unit { .. } => format!(
                "Disable and stop the systemd user service {unit}\n\
                 Remove its unit file {path}\n\
                 Reload the systemd user manager"
            ),
            Found::Orphan { .. } => format!(
                "Stop the systemd user service {unit}, whose unit file {path} is already gone\n\
                 Reload the systemd user manager"
            ),
        };
        let drop_ins = self.path.with_file_name(format!("{unit}.d"));
        if drop_ins.exists() {
            write!(
                text,
                "\nKeep the drop-in settings in {}",
                drop_ins.display()
            )
            .expect("write to string");
        }
        write!(text, "\nKeep the device profile, keys and logs in {dir}").expect("write to string");
        text
    }

    fn remove(&self, found: Found) -> Result<String> {
        let unit = self.unit;
        match found {
            Found::Nothing { .. } => return Ok(self.describe(&found)),
            Found::Unit { file, .. } => {
                // Immediately before the first change.
                ensure!(unit_file(self.path)?.as_ref() == Some(&file), CHANGED);
                // Disabled first: from here on it does not return at the next login.
                self.must(&["disable", unit])
                    .context("the service was not removed")?;
                self.stop().context(
                    "the service is disabled, and its unit file is kept. Run 'massrelay \
                     uninstall' again",
                )?;
                ensure!(
                    unit_file(self.path)?.as_ref() == Some(&file),
                    "{} changed while the service was stopping; it was not removed",
                    self.path.display()
                );
                fs::remove_file(self.path)
                    .with_context(|| format!("remove {}", self.path.display()))?;
            }
            Found::Orphan { .. } => {
                ensure!(unit_file(self.path)?.is_none(), CHANGED);
                // Only enablement links can be left of the file, and there may be none.
                let _ = (self.systemctl)(&["disable", unit]);
                self.stop()?;
            }
        }
        self.must(&["daemon-reload"]).context(
            "the service is stopped and its unit file removed, but systemd has not reloaded. \
             Run 'massrelay uninstall' again",
        )?;
        // Forget a failure the unit may have left behind; usually there is none.
        let _ = (self.systemctl)(&["reset-failed", unit]);
        Ok(format!("Removed {unit}"))
    }

    fn stop(&self) -> Result<()> {
        self.must(&["stop", self.unit])?;
        ensure!(
            stopped(&self.must(&["show", "--property=ActiveState", self.unit])?)?,
            "{} has not stopped",
            self.unit
        );
        Ok(())
    }

    /// A request that has to succeed. Returns what it printed.
    fn must(&self, args: &[&str]) -> Result<String> {
        let output = (self.systemctl)(args)?;
        ensure!(
            output.success,
            "systemctl --user {} failed: {}",
            args.join(" "),
            output.stderr.trim()
        );
        Ok(output.stdout)
    }
}

/// An installed service, for `massrelay update`.
pub struct Managed {
    dir: PathBuf,
    unit: String,
    path: PathBuf,
}

impl Managed {
    /// Hand the update to a separate user service, outside the daemon's session lifetime.
    pub(crate) fn queue_update(&self, program: &Path) -> Result<String> {
        let unit = self
            .unit
            .replacen("massrelay-client", "massrelay-update", 1);
        start_detached(&unit, program, &self.dir, &["update"], &[])
            .context("start a detached MassRelay update with systemd-run")?;
        Ok(format!(
            "Update queued as {unit}. Exit this shell so sessions can drain.\nUpdate log     journalctl --user -u {unit}"
        ))
    }
}

/// The property that keeps a queued command from taking itself to be inside a session.
fn unset_session() -> String {
    use crate::private::{HOST_ENV, SSH_ENV};
    format!("UnsetEnvironment={HOST_ENV} {SSH_ENV}")
}

pub fn managed(dir: &Path) -> Result<Managed> {
    let dir = dir
        .canonicalize()
        .context("resolve the device state directory")?;
    let (units, unit) = profile_unit(&dir)?;
    let path = units.join(&unit);
    ensure!(
        read_unit(&path)?.is_some(),
        "no installed service for this profile. Run massrelay install first"
    );
    ensure!(
        bounded(&["show-environment"])?.success,
        "could not reach your systemd user manager"
    );
    Ok(Managed { dir, unit, path })
}

impl crate::update::Service for Managed {
    fn label(&self) -> String {
        self.unit.clone()
    }

    fn events(&self) -> PathBuf {
        self.dir.join("connections.jsonl")
    }

    fn launches(&self, program: &Path) -> Result<bool> {
        let unit = read_unit(&self.path)?.context("the service unit was removed")?;
        if !starts(&String::from_utf8_lossy(&unit), program, &self.dir)? {
            return Ok(false);
        }
        // What the manager would run can differ from the file: a drop-in, or an edit it has
        // not loaded.
        let shown = bounded(&[
            "show",
            "--property=ExecStart",
            "--property=NeedDaemonReload",
            &self.unit,
        ])?;
        ensure!(shown.success, "systemctl --user show failed");
        loaded(&shown.stdout, program, &self.dir)
    }

    fn state(&self) -> Result<crate::update::Manager> {
        let shown = bounded(&[
            "show",
            "--property=ActiveState",
            "--property=MainPID",
            &self.unit,
        ])?;
        ensure!(shown.success, "systemctl --user show failed");
        manager_state(&shown.stdout)
    }

    fn start(&self) -> Result<()> {
        // A program that failed repeatedly may have exhausted the unit's start limit.
        let _ = bounded(&["reset-failed", &self.unit]);
        let started = bounded(&["start", &self.unit])?;
        ensure!(
            started.success,
            "systemctl --user start {} failed: {}",
            self.unit,
            started.stderr.trim()
        );
        Ok(())
    }
}

/// What `systemctl show` says of a unit, as the update reads it. Only `inactive` and `failed`
/// mean that nothing runs and nothing is about to: a unit that is activating (which includes
/// waiting for its automatic restart), deactivating or reloading is in between.
fn manager_state(shown: &str) -> Result<crate::update::Manager> {
    use crate::update::Manager;
    let property = |name: &str| {
        shown
            .lines()
            .find_map(|line| line.strip_prefix(name)?.strip_prefix('='))
            .with_context(|| format!("systemctl --user show printed no {name}"))
    };
    let pid: u32 = property("MainPID")?
        .trim()
        .parse()
        .context("read the service's process ID")?;
    Ok(match property("ActiveState")?.trim() {
        "active" if pid != 0 => Manager::Running(pid),
        "inactive" | "failed" => Manager::Stopped,
        state => Manager::Pending(format!("as {state}")),
    })
}

/// `systemctl --user`, within the limit an update gives one request to a service manager.
fn bounded(args: &[&str]) -> Result<crate::update::Finished> {
    crate::update::run_within(
        user_manager("systemctl").args(args),
        crate::update::MANAGER_LIMIT,
    )
    .context("run systemctl --user")
}

/// `program --user`. A MassRelay SSH session is not a login session, so nothing there sets
/// `XDG_RUNTIME_DIR`, without which systemd's tools cannot find the user manager.
fn user_manager(program: &str) -> Command {
    let mut command = Command::new(program);
    command.arg("--user");
    if env::var_os("XDG_RUNTIME_DIR").is_none() {
        // SAFETY: `getuid` has no preconditions and cannot fail.
        let uid = unsafe { libc::getuid() };
        command.env("XDG_RUNTIME_DIR", format!("/run/user/{uid}"));
    }
    command
}

/// Whether every command a generated unit starts is `program` running the profile in `dir`.
fn starts(unit: &str, program: &Path, dir: &Path) -> Result<bool> {
    let expected = format!(
        "ExecStart={} --state-dir {} run ",
        argument(program, ":")?,
        argument(dir, "")?
    );
    let mut commands = unit.lines().filter(|line| line.starts_with("ExecStart="));
    Ok(commands
        .next()
        .is_some_and(|line| line.starts_with(&expected))
        && commands.next().is_none())
}

/// Whether the unit as the manager has it loaded (`systemctl show`) starts only `program`
/// running the profile in `dir`, and matches the unit file on disk.
fn loaded(shown: &str, program: &Path, dir: &Path) -> Result<bool> {
    let text = |path: &Path| {
        path.to_str()
            .map(str::to_owned)
            .with_context(|| format!("path is not UTF-8: {}", path.display()))
    };
    let (program, dir) = (text(program)?, text(dir)?);
    let expected = format!("ExecStart={{ path={program} ; argv[]={program} --state-dir {dir} run ");
    let mut commands = shown.lines().filter(|line| line.starts_with("ExecStart="));
    Ok(commands
        .next()
        .is_some_and(|line| line.starts_with(&expected))
        && commands.next().is_none()
        && shown.lines().any(|line| line == "NeedDaemonReload=no"))
}

/// One value in `systemctl show` output.
fn property<'a>(shown: &'a str, name: &str) -> Result<&'a str> {
    shown
        .lines()
        .find_map(|line| line.strip_prefix(name)?.strip_prefix('='))
        .map(str::trim)
        .with_context(|| format!("systemctl --user show printed no {name}"))
}

/// Whether nothing of a unit runs or is about to.
fn stopped(shown: &str) -> Result<bool> {
    Ok(matches!(
        property(shown, "ActiveState")?,
        "inactive" | "failed"
    ))
}

/// Whether a generated unit's only command runs the profile in `dir`, with any program.
fn runs_profile(unit: &str, dir: &Path) -> Result<bool> {
    // A quote in a path is escaped, so this cannot match inside the program's own argument.
    let expected = format!("\" --state-dir {} run ", argument(dir, "")?);
    let mut commands = unit.lines().filter(|line| line.starts_with("ExecStart="));
    Ok(commands
        .next()
        .is_some_and(|line| line.starts_with("ExecStart=\":") && line.contains(&expected))
        && commands.next().is_none())
}

/// `runs_profile` for the unit as the manager has it loaded.
fn loaded_for(shown: &str, dir: &Path) -> Result<bool> {
    let dir = dir
        .to_str()
        .with_context(|| format!("path is not UTF-8: {}", dir.display()))?;
    let expected = format!(" --state-dir {dir} run ");
    let mut commands = shown.lines().filter(|line| line.starts_with("ExecStart="));
    Ok(commands.next().is_some_and(|line| line.contains(&expected)) && commands.next().is_none())
}

/// The commands in `systemctl show` output, without what the manager records of their runs.
fn loaded_commands(shown: &str) -> Vec<String> {
    shown
        .lines()
        .filter(|line| line.starts_with("ExecStart="))
        .map(|line| {
            line.split_once(" ; ignore_errors=")
                .map_or(line, |(command, _)| command)
                .to_owned()
        })
        .collect()
}

/// Whether two paths name one directory entry, which need not exist.
fn same_place(a: &Path, b: &Path) -> bool {
    let resolve = |path: &Path| Some(path.parent()?.canonicalize().ok()?.join(path.file_name()?));
    a == b || resolve(a).is_some_and(|a| resolve(b) == Some(a))
}

/// Whether a `/proc/PID/cgroup` listing places that process in `unit`.
fn in_unit(cgroups: &str, unit: &str) -> bool {
    cgroups
        .lines()
        .filter_map(|line| line.splitn(3, ':').nth(2))
        .any(|group| group.split('/').any(|part| part == unit))
}

fn profile_unit(dir: &Path) -> Result<(PathBuf, String)> {
    let default = default_state_dir()?.canonicalize().ok();
    let unit = unit_name(dir, default.as_deref());
    let user = BaseDirs::new().context("cannot find the user configuration directory")?;
    Ok((user.config_dir().join("systemd/user"), unit))
}

fn read_unit(path: &Path) -> Result<Option<Vec<u8>>> {
    match fs::symlink_metadata(path) {
        Ok(metadata) if metadata.is_file() => {
            let previous = fs::read(path)?;
            ensure!(
                previous.starts_with(GENERATED.as_bytes()),
                "an existing service uses {}",
                path.display()
            );
            Ok(Some(previous))
        }
        Ok(_) => bail!("expected a regular file at {}", path.display()),
        Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(None),
        Err(error) => Err(error.into()),
    }
}

/// The unit file at `path`, if there is one, which must be one `install` generated.
fn unit_file(path: &Path) -> Result<Option<UnitFile>> {
    use std::os::unix::fs::MetadataExt;

    let Some(contents) = read_unit(path)? else {
        return Ok(None);
    };
    let metadata = fs::symlink_metadata(path)?;
    Ok(Some(UnitFile {
        contents,
        written: (metadata.dev(), metadata.ino(), metadata.modified()?),
    }))
}

fn unit_name(dir: &Path, default: Option<&Path>) -> String {
    if default == Some(dir) {
        "massrelay-client.service".into()
    } else {
        let hash = Sha256::digest(dir.as_os_str().as_encoded_bytes());
        format!("massrelay-client-{hash:x}.service")
    }
}

fn render(binary: &Path, dir: &Path, log: &Path) -> Result<String> {
    // The colon prefix disables systemd's environment expansion for this command.
    let binary = argument(binary, ":")?;
    let dir = argument(dir, "")?;
    let log = argument(log, "")?;
    Ok(format!(
        "{GENERATED}\
[Unit]\n\
Description=MassRelay client\n\
\n\
[Service]\n\
Type=exec\n\
ExecStart={binary} --state-dir {dir} run --log-file {log}\n\
Restart=on-failure\n\
\n\
[Install]\n\
WantedBy=default.target\n"
    ))
}

fn argument(path: &Path, prefix: &str) -> Result<String> {
    let text = path
        .to_str()
        .with_context(|| format!("path is not UTF-8: {}", path.display()))?;
    let mut escaped = format!("\"{prefix}");
    for ch in text.chars() {
        match ch {
            '%' => escaped.push_str("%%"),
            '\\' => escaped.push_str("\\\\"),
            '"' => escaped.push_str("\\\""),
            ch if ch.is_control() => write!(escaped, "\\u{:04x}", u32::from(ch))?,
            ch => escaped.push(ch),
        }
    }
    escaped.push('"');
    Ok(escaped)
}

fn write_unit(path: &Path, contents: &[u8]) -> Result<()> {
    let mut staged = NamedTempFile::new_in(path.parent().expect("unit directory"))?;
    staged.write_all(contents)?;
    staged.as_file().sync_all()?;
    staged
        .persist(path)
        .with_context(|| format!("save {}", path.display()))?;
    Ok(())
}

fn user_command(args: &[&str]) -> Result<Output> {
    Command::new("systemctl")
        .arg("--user")
        .args(args)
        .output()
        .context("run systemctl --user")
}

fn systemctl(args: &[&str]) -> Result<()> {
    succeeded(args, user_command(args)?)?;
    Ok(())
}

/// Require that the request `args` succeeded.
fn succeeded(args: &[&str], output: Output) -> Result<Output> {
    ensure!(
        output.status.success(),
        "systemctl --user {} failed ({}): {}",
        args.join(" "),
        output.status,
        String::from_utf8_lossy(&output.stderr).trim()
    );
    Ok(output)
}

