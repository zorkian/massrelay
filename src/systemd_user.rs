    /// A user manager that knows one unit, for removal.
    struct Manager {
        path: PathBuf,
        /// What `show` says: whether the unit is loaded, running, and its main process.
        loaded: bool,
        active: bool,
        enabled: bool,
        fragment: Option<PathBuf>,
        exec: String,
        update: &'static str,
        /// A verb that fails, and whether any request can be made at all.
        refuse: Option<&'static str>,
        unreachable: bool,
        /// Every request that changes something.
        changes: Vec<String>,
    }

    impl Manager {
        fn run(state: &RefCell<Self>, args: &[&str]) -> Result<crate::update::Finished> {
            let mut manager = state.borrow_mut();
            ensure!(!manager.unreachable, "no user bus");
            let unit = *args.last().context("no unit")?;
            let mut stdout = String::new();
            let mut success = true;
            if args[0] == "show" {
                stdout = if unit.starts_with("massrelay-update") {
                    format!("ActiveState={}\n", manager.update)
                } else {
                    let fragment = manager.fragment.as_deref().filter(|_| manager.loaded);
                    format!(
                        "LoadState={}\nActiveState={}\nMainPID={}\nFragmentPath={}\n{}",
                        if manager.loaded {
                            "loaded"
                        } else {
                            "not-found"
                        },
                        if manager.active { "active" } else { "inactive" },
                        if manager.active { 4242 } else { 0 },
                        fragment.map_or_else(String::new, |path| path.display().to_string()),
                        manager.exec
                    )
                };
            } else {
                manager.changes.push(args[0].to_owned());
                success = manager.refuse != Some(args[0]);
                if success {
                    match args[0] {
                        "disable" => manager.enabled = false,
                        "stop" => manager.active = false,
                        "daemon-reload" => manager.loaded = manager.path.exists(),
                        _ => {}
                    }
                }
            }
            Ok(crate::update::Finished {
                success,
                stdout,
                stderr: if success {
                    String::new()
                } else {
                    "refused".into()
                },
            })
        }
    }

    #[test]
    fn uninstall_removes_only_this_profiles_service_and_can_be_repeated() -> Result<()> {
        let temp = tempfile::tempdir()?;
        let dir = temp.path().join("my profile");
        fs::create_dir(&dir)?;
        fs::write(dir.join("kept"), "enrollment")?;
        let unit = unit_name(&dir, None);
        let path = temp.path().join(&unit);
        let source = render(Path::new("/opt/massrelay"), &dir, &dir.join("log"))?;
        let exec = format!(
            "ExecStart={{ path=/opt/massrelay ; argv[]=/opt/massrelay --state-dir {} run --log-file x ; ignore_errors=no ; pid=7 }}\n",
            dir.display()
        );
        let manager = RefCell::new(Manager {
            path: path.clone(),
            loaded: true,
            active: true,
            enabled: true,
            fragment: Some(path.clone()),
            exec,
            update: "inactive",
            refuse: None,
            unreachable: false,
            changes: vec![],
        });
        let run = |args: &[&str]| Manager::run(&manager, args);
        let outside = "0::/user.slice/user@1000.service/app.slice/terminal.scope\n";
        let removal = Removal {
            dir: &dir,
            unit: &unit,
            path: &path,
            cgroups: outside,
            shell_host: None,
            systemctl: &run,
        };
        // As the command does it: shown, then applied to what was shown.
        let uninstall = |removal: &Removal| {
            let shown = removal.inspect()?;
            removal.remove(removal.confirm(&shown)?)
        };
        let changes = || std::mem::take(&mut manager.borrow_mut().changes);
        let refused = |removal: &Removal| {
            let before = fs::read(&path).ok();
            let error = format!("{:#}", uninstall(removal).unwrap_err());
            assert_eq!(fs::read(&path).ok(), before, "{error}");
            assert!(changes().is_empty(), "{error}");
        };

        // Files that are not this profile's generated unit, and a link in their place.
        let other = render(Path::new("/opt/massrelay"), temp.path(), &dir.join("log"))?;
        for foreign in ["[Service]\nExecStart=/bin/true\n", &other] {
            fs::write(&path, foreign)?;
            refused(&removal);
        }
        fs::remove_file(&path)?;
        let target = temp.path().join("elsewhere");
        fs::write(&target, &source)?;
        std::os::unix::fs::symlink(&target, &path)?;
        refused(&removal);
        fs::remove_file(&path)?;
        fs::write(&path, &source)?;

        // The manager has the name from another file.
        manager.borrow_mut().fragment = Some(target.clone());
        refused(&removal);
        manager.borrow_mut().fragment = Some(path.clone());

        // The command would end with the service: by its control group, or its shell's host.
        let inside = format!("0::/user.slice/user@1000.service/app.slice/{unit}\n");
        refused(&Removal {
            cgroups: &inside,
            ..removal
        });
        refused(&Removal {
            shell_host: Some(4242),
            ..removal
        });
        manager.borrow_mut().update = "activating";
        refused(&removal);
        manager.borrow_mut().update = "inactive";
        manager.borrow_mut().unreachable = true;
        refused(&removal);
        manager.borrow_mut().unreachable = false;

        // Looking, as a confirmation does, changes nothing.
        let shown = removal.inspect()?;
        let plan = removal.describe(&shown);
        assert!(plan.contains(&unit) && plan.contains(path.to_str().unwrap()));
        assert!(changes().is_empty());
        // A restart in the meantime leaves the registration as it was.
        let restarted = manager.borrow().exec.replace("pid=7", "pid=8");
        manager.borrow_mut().exec = restarted;
        removal.confirm(&shown)?;

        // Nothing shown, or one registration shown: another is not removed in its place,
        // whether the file was written anew, even alike, or the manager loaded something else.
        fs::remove_file(&path)?;
        manager.borrow_mut().loaded = false;
        manager.borrow_mut().active = false;
        let nothing = removal.inspect()?;
        removal.confirm(&nothing)?;
        write_unit(&path, source.as_bytes())?;
        manager.borrow_mut().loaded = true;
        manager.borrow_mut().active = true;
        assert!(removal.confirm(&nothing).is_err());
        let shown = removal.inspect()?;
        for contents in [
            source.clone(),
            source.replace("/opt/massrelay", "/opt/other"),
        ] {
            // The earlier file is kept open, so that its inode is not used again.
            let _earlier = fs::File::open(&path)?;
            write_unit(&path, contents.as_bytes())?;
            assert!(removal.confirm(&shown).is_err());
        }
        write_unit(&path, source.as_bytes())?;
        let shown = removal.inspect()?;
        let exec = manager.borrow().exec.clone();
        manager.borrow_mut().exec = exec.replace("/opt/massrelay", "/opt/other");
        assert!(removal.confirm(&shown).is_err());
        manager.borrow_mut().exec = exec;
        // Replaced after the last inspection, right before the first change.
        let confirmed = removal.confirm(&shown)?;
        let _earlier = fs::File::open(&path)?;
        write_unit(&path, source.as_bytes())?;
        assert!(removal.remove(confirmed).is_err());
        assert!(changes().is_empty());
        assert_eq!(fs::read_to_string(&path)?, source);

        // A service that does not stop keeps its file, and is no longer enabled.
        manager.borrow_mut().refuse = Some("stop");
        assert!(uninstall(&removal).is_err());
        assert_eq!(changes(), ["disable", "stop"]);
        assert_eq!(fs::read_to_string(&path)?, source);
        assert!(!manager.borrow().enabled);

        // A repeat finishes it, here with a reload that fails after the file is gone.
        manager.borrow_mut().refuse = Some("daemon-reload");
        assert!(uninstall(&removal).is_err());
        assert_eq!(changes(), ["disable", "stop", "daemon-reload"]);
        assert!(!path.exists());

        // What the manager still holds is matched to the profile before it is touched.
        manager.borrow_mut().refuse = None;
        let exec = std::mem::take(&mut manager.borrow_mut().exec);
        refused(&removal);
        manager.borrow_mut().exec = exec;
        uninstall(&removal)?;
        assert_eq!(
            changes(),
            ["disable", "stop", "daemon-reload", "reset-failed"]
        );

        // Nothing left: success, with or without a manager to ask.
        uninstall(&removal)?;
        manager.borrow_mut().unreachable = true;
        uninstall(&removal)?;
        assert!(changes().is_empty());
        assert_eq!(fs::read_to_string(dir.join("kept"))?, "enrollment");
        assert_eq!(fs::read_to_string(&target)?, source);
        Ok(())
    }

    #[test]
    fn an_install_applies_only_over_what_was_shown() -> Result<()> {
        use std::os::unix::process::ExitStatusExt;

        let temp = tempfile::tempdir()?;
        let dir = temp.path().join("profile");
        let units = temp.path().join("units");
        let unit = unit_name(&dir, None);
        let path = units.join(&unit);
        // Whether the unit is active and enabled, and what `show` says is loaded.
        let manager = RefCell::new((false, false, String::from("FragmentPath=\n")));
        let systemctl = |args: &[&str]| {
            let (active, enabled, shown) = &*manager.borrow();
            let success = match args[0] {
                "show-environment" | "show" => true,
                "is-active" => *active,
                "is-enabled" => *enabled,
                other => bail!("looking asked the manager to {other}"),
            };
            Ok(Output {
                status: std::process::ExitStatus::from_raw(i32::from(!success) << 8),
                stdout: shown.clone().into_bytes(),
                stderr: vec![],
            })
        };
        let read = |binary: &str| {
            let target = (units.clone(), unit.clone());
            Prepared::read(dir.clone(), target, binary.into(), &systemctl)
        };
        let refused = |plan: &InstallPlan, binary: &str| {
            assert!(plan.confirm(read(binary).unwrap()).is_err());
        };

        // Nothing is installed, and looking makes nothing.
        let plan = InstallPlan::new(read("/opt/massrelay")?);
        plan.confirm(read("/opt/massrelay")?)?;
        assert!(!units.exists());
        // Another program would be installed.
        refused(&plan, "/opt/other");
        manager.borrow_mut().1 = true;
        refused(&plan, "/opt/massrelay");
        manager.borrow_mut().1 = false;
        // A unit installed since is not replaced.
        fs::create_dir(&units)?;
        write_unit(&path, GENERATED.as_bytes())?;
        refused(&plan, "/opt/massrelay");

        let loaded = |program: &str, pid: u32| {
            format!(
                "FragmentPath={}\nExecStart={{ path={program} ; argv[]={program} ; ignore_errors=no ; pid={pid} }}\n",
                path.display()
            )
        };
        manager.borrow_mut().2 = loaded("/opt/massrelay", 7);
        let plan = InstallPlan::new(read("/opt/massrelay")?);
        manager.borrow_mut().2 = loaded("/opt/massrelay", 8);
        plan.confirm(read("/opt/massrelay")?)?;
        manager.borrow_mut().2 = loaded("/opt/other", 8);
        refused(&plan, "/opt/massrelay");
        manager.borrow_mut().2 = loaded("/opt/massrelay", 8);
        // It started: replacing it now would end its sessions.
        manager.borrow_mut().0 = true;
        refused(&plan, "/opt/massrelay");
        manager.borrow_mut().0 = false;
        // The file was written anew, even alike.
        let _earlier = fs::File::open(&path)?;
        write_unit(&path, GENERATED.as_bytes())?;
        refused(&plan, "/opt/massrelay");
        assert_eq!(fs::read_to_string(&path)?, GENERATED);
        assert_eq!(fs::read_dir(&units)?.count(), 1);
        Ok(())
    }

    #[test]
    fn a_carried_install_restarts_only_if_the_saved_service_can_be_restored() -> Result<()> {
        use std::os::unix::process::ExitStatusExt;

        let temp = tempfile::tempdir()?;
        let dir = temp.path().join("profile");
        let units = temp.path().join("units");
        let binary = temp.path().join("massrelay");
        fs::write(&binary, "program")?;
        let other = temp.path().join("other");
        fs::write(&other, "program")?;
        fs::create_dir(&units)?;
        let unit = unit_name(&dir, None);
        let path = units.join(&unit);
        let source = render(&binary, &dir, &dir.join("connections.jsonl"))?;
        let runtime = Identity {
            pid: 4242,
            executable: binary.to_str().map(str::to_owned),
            version: env!("CARGO_PKG_VERSION").into(),
            endpoint: String::new(),
            held: false,
        };
        // What the manager says: active, enabled, the running command, and whether the file
        // has changed since it was loaded.
        let drop_ins = std::cell::Cell::new("");
        let carried = |active: bool, enabled: bool, reload: &str, runtime: &Identity| {
            let systemctl = |args: &[&str]| {
                let success = match args[0] {
                    "show-environment" | "show" => true,
                    "is-active" => active,
                    "is-enabled" => enabled,
                    other => bail!("looking asked the manager to {other}"),
                };
                let shown = format!(
                    "MainPID=4242\nFragmentPath={}\nExecStart={{ path={binary} ; argv[]={binary} \
                     --state-dir {} run --log-file x ; ignore_errors=no ; pid=4242 }}\n\
                     NeedDaemonReload={reload}\nDropInPaths={}\n",
                    path.display(),
                    dir.display(),
                    drop_ins.get(),
                    binary = binary.display(),
                );
                Ok(Output {
                    status: std::process::ExitStatus::from_raw(i32::from(!success) << 8),
                    stdout: shown.into_bytes(),
                    stderr: vec![],
                })
            };
            let target = (units.clone(), unit.clone());
            let read = Prepared::read(dir.clone(), target, binary.clone(), &systemctl)?;
            let mut plan = InstallPlan::new(read);
            let replacing = plan.approval();
            plan.inspect_carrier(runtime, &systemctl)?;
            // A finishing process cannot take keeping for replacing.
            assert_eq!(plan.approval() != replacing, plan.keeps());
            anyhow::Ok(plan.keeps())
        };

        write_unit(&path, source.as_bytes())?;
        assert!(carried(true, true, "no", &runtime)?);
        assert!(!carried(true, false, "no", &runtime)?);
        assert!(carried(true, true, "yes", &runtime)?);
        // An older release, a runtime retiring for an update, and a replaced program, which
        // Linux names as deleted.
        let deleted = format!("{} (deleted)", binary.display());
        for usable in [
            Identity {
                version: "0.0.1".into(),
                ..runtime.clone()
            },
            Identity {
                held: true,
                ..runtime.clone()
            },
        ] {
            assert!(!carried(true, true, "no", &usable)?);
        }
        for stale in [
            Identity {
                executable: Some(deleted),
                ..runtime.clone()
            },
            Identity {
                executable: other.to_str().map(str::to_owned),
                ..runtime.clone()
            },
        ] {
            assert!(carried(true, true, "no", &stale)?, "{stale:?}");
        }
        // A runtime the service does not run is not replaced from its own session.
        let foreground = Identity {
            pid: 7,
            ..runtime.clone()
        };
        assert!(carried(true, true, "no", &foreground).is_err());
        assert!(carried(false, true, "no", &runtime).is_err());
        let older = Identity {
            version: "0.0.1".into(),
            ..runtime.clone()
        };
        assert!(!carried(true, true, "no", &older)?);
        assert!(carried(true, true, "yes", &older)?);
        drop_ins.set("/etc/systemd/user/service.d/overrides.conf");
        assert!(carried(true, true, "no", &older)?);
        drop_ins.set("");
        write_unit(
            &path,
            format!("{source}ExecStartPre=/bin/false\n").as_bytes(),
        )?;
        assert!(carried(true, true, "no", &older)?);
        write_unit(
            &path,
            render(&other, &dir, &dir.join("connections.jsonl"))?.as_bytes(),
        )?;
        assert!(carried(true, true, "no", &older)?);
        fs::remove_file(&path)?;
        assert!(carried(true, true, "yes", &older)?);
        write_unit(&path, source.as_bytes())?;
        assert_eq!(fs::read_dir(&units)?.count(), 1);
        Ok(())
    }

    /// Stands for the command in a session of the service: run inside a unit by the test
