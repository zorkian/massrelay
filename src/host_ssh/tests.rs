#[test]
#[ignore = "needs the system OpenSSH server"]
fn an_interrupted_change_is_reloaded_before_it_counts_as_done() -> Result<()> {
    let fixture = Fixture::new("")?;
    let profile = fixture.profile("state")?;
    let original = fixture.contents();
    fixture.install(&profile)?.apply()?;
    let installed = fixture.contents();
    let keys = fs::read_to_string(profile.join(AUTHORIZED_KEYS))?;
    fixture.uninstall(&profile)?.apply()?;
    let at_replace = fs::read_to_string(fixture.root().join("record-at-replace"))?;
    assert!(
        at_replace.contains("\"reload_pending\":true"),
        "{at_replace}"
    );

    // The state such a removal leaves if it stops right after replacing the file.
    let interrupted = || -> Result<()> {
        fixture.write_config(&original)?;
        file(&profile.join(AUTHORIZED_KEYS), &keys, 0o600)?;
        file(&profile.join(SETUP_RECORD), &at_replace, 0o600)?;
        fixture.log();
        Ok(())
    };
    interrupted()?;
    fs::write(fixture.root().join("fail-all-reloads"), "")?;
    for _ in 0..2 {
        let plan = fixture.uninstall(&profile)?;
        assert!(plan.to_string().contains("still owes"), "{plan}");
        refused(plan.apply(), "still has not reloaded");
        assert_eq!(fixture.reloads(), 1);
        assert!(
            fs::read_to_string(profile.join(SETUP_RECORD))?.contains("\"reload_pending\":true")
        );
    }
    fs::remove_file(fixture.root().join("fail-all-reloads"))?;
    fixture.uninstall(&profile)?.apply()?;
    assert_eq!(fixture.reloads(), 1);
    assert_unconfigured(&profile);
    assert_eq!(fixture.contents(), original);

    // A running server can still hold the old configuration after the file disappears.
    interrupted()?;
    fs::remove_file(fixture.config())?;
    fixture.uninstall(&profile)?.apply()?;
    assert_eq!(fixture.reloads(), 0);
    assert!(fs::read_to_string(profile.join(SETUP_RECORD))?.contains("\"reload_pending\":true"));
    fixture.write_config(&original)?;
    fixture.uninstall(&profile)?.apply()?;
    assert_eq!(fixture.reloads(), 1);
    assert_unconfigured(&profile);

    // A stopped server owes nothing: it reads the present file when it starts.
    interrupted()?;
    fixture.stop_service()?;
    fixture.uninstall(&profile)?.apply()?;
    assert_eq!(fixture.reloads(), 0);
    assert_unconfigured(&profile);
    fixture.service("")?;

    // Another account's record is not reconciled by this one.
    interrupted()?;
    let other = at_replace.replace(&format!("\"{}\"", user()), "\"someone-else\"");
    assert_ne!(other, at_replace);
    file(&profile.join(SETUP_RECORD), &other, 0o600)?;
    refused(fixture.uninstall(&profile), "someone-else");
    refused(fixture.install(&profile), "someone-else");
    assert_eq!(fixture.log(), Vec::<String>::new());

    // An install that stopped there is reloaded by the next one.
    interrupted()?;
    fixture.write_config(&installed)?;
    fixture.install(&profile)?.apply()?;
    assert_eq!(fixture.contents(), installed);
    assert_eq!(fixture.reloads(), 1);
    Server::load(&profile)?;
    fixture.assert_clean();
    Ok(())
}

