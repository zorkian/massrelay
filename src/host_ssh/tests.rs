#[test]
#[ignore = "needs the system OpenSSH server"]
fn two_profiles_share_an_account_and_leave_in_either_order() -> Result<()> {
    for first_leaves_first in [true, false] {
        let fixture = Fixture::new("")?;
        let original = fixture.contents();
        let one = fixture.profile("one two")?;
        let two = fixture.profile("three")?;
        fixture.install(&one)?.apply()?;
        fixture.install(&two)?.apply()?;
        let entry = |profile: &Path| profile.join(AUTHORIZED_KEYS).display().to_string();
        let both = fixture.key_files()?;
        assert!(
            both.contains(&entry(&one)) && both.contains(&entry(&two)),
            "{both}"
        );
        // Running the first again must not list anything twice.
        fixture.install(&one)?.apply()?;
        let again = fixture.key_files()?;
        assert_eq!(again.matches(&entry(&one)).count(), 1, "{again}");
        assert_eq!(again.matches(&entry(&two)).count(), 1, "{again}");

        let (leaving, staying) = if first_leaves_first {
            (&one, &two)
        } else {
            (&two, &one)
        };
        fixture.uninstall(leaving)?.apply()?;
        let left = fixture.key_files()?;
        assert!(!left.contains(&entry(leaving)), "{left}");
        assert!(left.contains(&entry(staying)), "{left}");
        assert!(left.starts_with(".ssh/authorized_keys "), "{left}");
        Server::load(staying)?;
        fixture.uninstall(staying)?.apply()?;
        assert_eq!(fixture.contents(), original);
    }
    Ok(())
}

#[test]
#[ignore = "needs the system OpenSSH server"]
fn a_failed_reload_or_denied_rights_leave_the_previous_state() -> Result<()> {
    let fixture = Fixture::new("")?;
    let profile = fixture.profile("state")?;
    let original = fixture.contents();
    let untouched = |fixture: &Fixture| {
        assert_eq!(fixture.contents(), original);
        assert_unconfigured(&profile);
        fixture.assert_clean();
    };

    let denied = fixture.root().join("deny-sudo");
    fs::write(&denied, "")?;
    refused(fixture.install(&profile)?.apply(), "administrator rights");
    untouched(&fixture);
    fs::remove_file(denied)?;

    // Changed after it was shown.
    let plan = fixture.install(&profile)?;
    let changed = format!("{original}# edited meanwhile\n");
    fixture.write_config(&changed)?;
    refused(plan.apply(), "changed after the changes were shown");
    assert_eq!(fixture.contents(), changed);
    assert_unconfigured(&profile);
    fixture.write_config(&original)?;
    fixture.log();

    fs::write(fixture.root().join("fail-reload"), "")?;
    refused(fixture.install(&profile)?.apply(), "was restored");
    untouched(&fixture);
    assert_eq!(fixture.reloads(), 2);

    // A failed removal keeps the setup working and can be run again.
    fixture.install(&profile)?.apply()?;
    let installed = fixture.contents();
    let server = Server::load(&profile)?;
    let kept = fs::read(profile.join(SETUP_RECORD))?;
    fs::write(fixture.root().join("fail-reload"), "")?;
    refused(fixture.uninstall(&profile)?.apply(), "was restored");
    assert_eq!(fixture.contents(), installed);
    assert_eq!(Server::load(&profile)?, server);
    assert_eq!(fs::read(profile.join(SETUP_RECORD))?, kept);
    fixture.uninstall(&profile)?.apply()?;
    untouched(&fixture);
    Ok(())
}

#[test]
#[ignore = "needs the system OpenSSH server"]
fn removal_waits_for_the_runtime_and_leaves_it_nothing_to_write() -> Result<()> {
    let fixture = Fixture::new("")?;
    let profile = fixture.profile("state")?;
    fixture.install(&profile)?.apply()?;
    let plan = fixture.uninstall(&profile)?;
    let held = lock(&profile, AUTHORIZED_KEYS_LOCK)?;
    let (done, finished) = mpsc::channel();
    let removal = thread::spawn(move || done.send(plan.apply()));
    assert!(finished.recv_timeout(Duration::from_millis(500)).is_err());
    // The runtime still sees a complete setup while it holds the lock.
    Server::load(&profile)?;
    drop(held);
    finished.recv_timeout(Duration::from_secs(30))??;
    removal.join().expect("removal thread")?;
    let _held = lock(&profile, AUTHORIZED_KEYS_LOCK)?;
    assert!(Server::load(&profile).unwrap_err().is::<Unavailable>());
    Ok(())
}

#[test]
#[ignore = "needs the system OpenSSH server"]
fn an_install_leaves_the_runtimes_lock_free_while_the_server_reloads() -> Result<()> {
    let fixture = Fixture::new("")?;
    let profile = fixture.profile("state")?;
    let hold = fixture.root().join("hold-reload");
    let reloading = fixture.root().join("reloading");
    // A first install, which nothing is authorized under before the reload, and then one
    // over a working setup, whose logins are authorized throughout.
    for working in [false, true] {
        if working {
            record(&profile, "made", true)?;
        }
        let plan = fixture.install(&profile)?;
        fs::write(&hold, "")?;
        let (done, finished) = mpsc::channel();
        let install = thread::spawn(move || done.send(plan.apply()));
        for _ in 0..600 {
            if reloading.exists() {
                break;
            }
            thread::sleep(Duration::from_millis(50));
        }
        let observed = (|| {
            ensure!(reloading.exists(), "the install never reloaded");
            let keys = fs::File::open(profile.join(AUTHORIZED_KEYS_LOCK))?;
            fs2::FileExt::try_lock_exclusive(&keys).context("the runtime's lock is held")?;
            ensure!(Server::load(&profile).is_ok() == working);
            // A removal of this profile still has to wait.
            let setup = fs::File::open(profile.join(SETUP_LOCK))?;
            ensure!(fs2::FileExt::try_lock_exclusive(&setup).is_err());
            Ok(())
        })();
        fs::remove_file(&hold)?;
        finished.recv_timeout(Duration::from_secs(30))??;
        install.join().expect("install thread")?;
        observed?;
        fs::remove_file(&reloading)?;
        Server::load(&profile)?;
        fixture.assert_clean();
    }
    // A removal that needs no rights waits for an install of its profile all the same.
    let other = fixture.profile("other")?;
    let held = lock(&other, SETUP_LOCK)?;
    record(&other, "making", false)?;
    let plan = fixture.uninstall(&other)?;
    let (done, finished) = mpsc::channel();
    let removal = thread::spawn(move || done.send(plan.apply()));
    assert!(finished.recv_timeout(Duration::from_millis(500)).is_err());
    assert!(other.join(SETUP_RECORD).exists());
    drop(held);
    finished.recv_timeout(Duration::from_secs(30))??;
    removal.join().expect("removal thread")?;
    assert_unconfigured(&other);
    Ok(())
}

