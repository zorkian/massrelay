//! What setup owns in a profile: the record of what it has made, and the key file.
//!
//! The key file is ours only if the record says an install made it and it still starts with
//! the line every install puts there. The record is written before the file, so an install
//! that stops between the two is recognized. A file without that proof is never adopted,
//! changed or removed, whatever its permissions.

use std::{
    fs,
    io::{self, Read as _},
    path::Path,
};

use anyhow::{Context, Result, ensure};
use serde::{Deserialize, Serialize};

use super::{
    AUTHORIZED_KEYS, SETUP_RECORD, ed25519, present, private_content_exists, remove, setup::System,
    write_private,
};

/// The first line of a key file an install made. The runtime keeps comments as they are.
const HEADER: &str = "# Generated by massrelay install for temporary SSH tunnel keys only.\n";
/// How the runtime starts and tags the line for a tunnel's key.
const OPTIONS: &str = "from=\"127.0.0.1\",expiry-time=\"";
const TAG: &str = "massrelay-lease:";
const RECORD_LIMIT: u64 = 4096;

/// Whether `line` is exactly in the form the runtime writes for a tunnel's key.
fn generated(line: &str) -> bool {
    let mut fields = line.split(' ');
    let expiry = fields
        .next()
        .and_then(|field| field.strip_prefix(OPTIONS)?.strip_suffix('"'));
    let (Some(expiry), Some(kind), Some(blob), Some(tag), None) = (
        expiry,
        fields.next(),
        fields.next(),
        fields.next(),
        fields.next(),
    ) else {
        return false;
    };
    let hex = |text: &str| !text.is_empty() && text.bytes().all(|b| b.is_ascii_hexdigit());
    expiry.len() == 14
        && expiry.bytes().all(|b| b.is_ascii_digit())
        && ed25519(&format!("{kind} {blob}")).is_some()
        && tag
            .strip_prefix(TAG)
            .and_then(|tag| tag.split_once(':'))
            .is_some_and(|(owner, id)| hex(owner) && hex(id))
}

/// Whether sshd could take a key from some line that the runtime did not write.
fn authorizes_others(contents: &str) -> bool {
    contents
        .lines()
        .map(str::trim)
        .any(|line| !line.is_empty() && !line.starts_with('#') && !generated(line))
}

/// What is left of our key file once the runtime's lines are gone, if anything but the
/// header and blank lines is: someone else wrote that, comments included.
fn others(contents: &str) -> Option<String> {
    let kept: String = contents
        .split_inclusive('\n')
        .filter(|line| !generated(line.trim()))
        .collect();
    let theirs = kept
        .split_inclusive('\n')
        .enumerate()
        .any(|(number, line)| !(line.trim().is_empty() || number == 0 && line == HEADER));
    theirs.then_some(kept)
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub(super) enum KeyFile {
    /// No install claims the file.
    #[default]
    Unclaimed,
    /// An install is about to make it, so only exactly what it writes is ours.
    Making,
    Made,
}

/// What setup has made for a profile and what it still has to finish.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub(super) struct Record {
    /// The account the server was set up for.
    user: String,
    pub key_file: KeyFile,
    /// The configuration may have been replaced without the server having reloaded it.
    pub reload_pending: bool,
}

impl Record {
    fn new(user: &str) -> Self {
        Self {
            user: user.to_owned(),
            key_file: KeyFile::Unclaimed,
            reload_pending: false,
        }
    }

    fn read(profile: &Path) -> Result<Option<Self>> {
        let path = profile.join(SETUP_RECORD);
        if !private_content_exists(&path)? {
            return Ok(None);
        }
        let contents = read(&path, RECORD_LIMIT)?;
        serde_json::from_slice(&contents)
            .map(Some)
            .with_context(|| format!("read {}", path.display()))
    }

    fn check_user(self, user: &str) -> Result<Self> {
        ensure!(
            self.user == user,
            "this profile records an SSH setup for the account {:?}, not {user:?}. Run the \
             command as that account",
            self.user
        );
        Ok(self)
    }

    /// The profile's record, or an empty one. Fails for one that cannot be used or that
    /// belongs to another account.
    pub(super) fn load(profile: &Path, user: &str) -> Result<Self> {
        match Self::read(profile)? {
            Some(record) => record.check_user(user),
            None => Ok(Self::new(user)),
        }
    }

    /// `load`, for removal, which an unreadable or unsafe record must not stop. Such a
    /// record claims nothing, is taken to owe a reload, comes with the reason, and is left
    /// alone. Another account's record still stops the removal.
    pub(super) fn load_for_removal(profile: &Path, user: &str) -> Result<(Self, Option<String>)> {
        match Self::read(profile) {
            Ok(Some(record)) => Ok((record.check_user(user)?, None)),
            Ok(None) => Ok((Self::new(user), None)),
            Err(error) => {
                let mut record = Self::new(user);
                record.reload_pending = true;
                Ok((
                    record,
                    Some(format!("the setup record is kept, and not used: {error:#}")),
                ))
            }
        }
    }

    pub(super) fn save(&self, profile: &Path) -> Result<()> {
        write_private(&profile.join(SETUP_RECORD), &serde_json::to_vec(self)?)
    }

    /// Keep the record only while it says something.
    pub(super) fn settle(&self, profile: &Path) -> Result<()> {
        if self.key_file == KeyFile::Unclaimed && !self.reload_pending {
            remove(&profile.join(SETUP_RECORD))
        } else {
            self.save(profile)
        }
    }
}

fn read(path: &Path, limit: u64) -> Result<Vec<u8>> {
    let mut contents = Vec::new();
    fs::File::open(path)
        .and_then(|file| file.take(limit + 1).read_to_end(&mut contents))
        .with_context(|| format!("read {}", path.display()))?;
    ensure!(
        contents.len() as u64 <= limit,
        "{} is too large",
        path.display()
    );
    Ok(contents)
}

/// All of a key file, which holds a line for each of however many tunnels are opening.
fn read_key_file(path: &Path) -> Result<Vec<u8>> {
    fs::read(path).with_context(|| format!("read {}", path.display()))
}

/// Refuse to set up with a key file that is not provably ours, or that would authorize a key
/// the runtime did not write.
pub(super) fn check_adoptable(system: &dyn System, profile: &Path, record: &Record) -> Result<()> {
    let path = profile.join(AUTHORIZED_KEYS);
    system.check_key_file(&path)?;
    if !present(&path)? {
        return Ok(());
    }
    ensure!(
        record.key_file != KeyFile::Unclaimed,
        "{} exists, and MassRelay did not make it, so the SSH server is not given it. It is \
         left as it is; move it elsewhere and run 'massrelay install' again",
        path.display()
    );
    let contents = String::from_utf8(read_key_file(&path)?).ok();
    let ours = contents
        .as_deref()
        .is_some_and(|contents| match record.key_file {
            KeyFile::Making => contents == HEADER,
            _ => contents.starts_with(HEADER) && !authorizes_others(contents),
        });
    ensure!(
        ours,
        "{} holds lines MassRelay did not write, or has lost its first line, so the SSH \
         server is not given it. It is left as it is; move it elsewhere and run 'massrelay \
         install' again",
        path.display()
    );
    Ok(())
}

/// Make the key file if there is none, claiming it first. True if it was made now.
pub(super) fn make_key_file(profile: &Path, record: &mut Record) -> Result<bool> {
    let path = profile.join(AUTHORIZED_KEYS);
    if present(&path)? {
        // `check_adoptable` proved it ours.
        if record.key_file != KeyFile::Made {
            record.key_file = KeyFile::Made;
            record.save(profile)?;
        }
        return Ok(false);
    }
    record.key_file = KeyFile::Making;
    record.save(profile)?;
    let mut staged = super::private_file(profile)?;
    io::Write::write_all(&mut staged, HEADER.as_bytes())?;
    staged.as_file().sync_all()?;
    // Never over a file that appeared meanwhile.
    staged
        .persist_noclobber(&path)
        .map_err(|error| error.error)
        .with_context(|| format!("create {}", path.display()))?;
    super::sync_directory(profile);
    record.key_file = KeyFile::Made;
    record.save(profile)?;
    Ok(true)
}

/// What removal does with the key file.
#[derive(Debug, PartialEq, Eq)]
pub(super) enum Disposition {
    Absent,
    /// Ours entirely.
    Remove,
    /// Ours, with lines someone else added, which are all that is left.
    Scrub(String),
    /// Not shown to be ours, and why.
    Keep(String),
}

pub(super) fn disposition(
    system: &dyn System,
    profile: &Path,
    record: &Record,
) -> Result<Disposition> {
    let path = profile.join(AUTHORIZED_KEYS);
    if !present(&path)? {
        return Ok(Disposition::Absent);
    }
    if record.key_file == KeyFile::Unclaimed {
        return Ok(Disposition::Keep("MassRelay did not make it".into()));
    }
    let contents = system
        .check_key_file(&path)
        .and_then(|()| Ok(String::from_utf8(read_key_file(&path)?)?));
    Ok(match contents {
        Err(error) => Disposition::Keep(format!("{error:#}")),
        Ok(contents) if !contents.starts_with(HEADER) => {
            Disposition::Keep("it no longer starts with the line an install writes".into())
        }
        Ok(contents) if record.key_file == KeyFile::Making && contents != HEADER => {
            Disposition::Keep("it is not what an interrupted install writes".into())
        }
        Ok(contents) => others(&contents).map_or(Disposition::Remove, Disposition::Scrub),
    })
}

#[cfg(test)]
mod tests {
    use base64::{Engine as _, engine::general_purpose::STANDARD};

    use super::*;

    #[test]
    fn only_the_runtimes_exact_lines_count_as_generated() {
        let blob = STANDARD.encode([&b"\0\0\0\x0bssh-ed25519\0\0\0\x20"[..], &[7; 32]].concat());
        let key = format!("ssh-ed25519 {blob}");
        let line = format!("{OPTIONS}20300101000000\" {key} {TAG}00aa:11");
        assert!(generated(&line));
        for other in [
            key.clone(),
            format!("{key} {TAG}00aa:11"),
            line.replace("127.0.0.1", "0.0.0.0/0"),
            line.replace("\",expiry", "\",pty,expiry"),
            line.replace("20300101000000", "forever"),
            format!("{line} trailing"),
            format!("command=\"x\",{line}"),
        ] {
            assert!(!generated(&other), "{other}");
            assert!(authorizes_others(&format!("{HEADER}{line}\n{other}\n")));
        }
        let ours = format!("{HEADER}\n{line}\r\n");
        assert!(!authorizes_others(&format!("{ours}# a note\n")));
        assert_eq!(others(&ours), None);
        assert_eq!(
            others(&format!("{ours}# a note\n{key}")),
            Some(format!("{HEADER}\n# a note\n{key}"))
        );
    }
}
